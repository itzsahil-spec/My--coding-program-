-- 9. Distinct students, age and birth month
SELECT NAME,
       FLOOR(MONTHS_BETWEEN(SYSDATE, BIRTHDAY) / 12) AS AGE,
       TO_CHAR(BIRTHDAY, 'FMMonth') AS BIRTH_MONTH
FROM (
    SELECT ROLL, NAME, DEPT, BIRTHDAY FROM SPORTS_STUD
    UNION
    SELECT ROLL, NAME, DEPT, BIRTHDAY FROM CULTURAL_STUD
);

-- 10. Last day of birth month for all students; UNION removes duplicate dates
SELECT LAST_DAY(BIRTHDAY) AS LAST_DAY FROM SPORTS_STUD
UNION
SELECT LAST_DAY(BIRTHDAY) AS LAST_DAY FROM CULTURAL_STUD;

-- 11. Sports student details in the requested sentence format
SELECT NAME || ' who studies in ' || DEPT ||
       ' dept pays Rs' || SPORTS_FEE || ' for sports.' AS STUDENT_DETAILS
FROM SPORTS_STUD;

-- 12A. Details of IT students from both tables
SELECT ROLL, NAME, DEPT, SPORTS_FEE AS FEES
FROM SPORTS_STUD
WHERE DEPT = 'IT'
UNION ALL
SELECT ROLL, NAME, DEPT, CUL_FEES AS FEES
FROM CULTURAL_STUD
WHERE DEPT = 'IT';

-- 12B. Total money collected by each group
SELECT 'SPORTS' AS DEPARTMENT, SUM(SPORTS_FEE) AS TOTAL_MONEY
FROM SPORTS_STUD
UNION ALL
SELECT 'CULTURAL' AS DEPARTMENT, SUM(CUL_FEES) AS TOTAL_MONEY
FROM CULTURAL_STUD;

-- 13. All distinct student names in descending order
SELECT NAME
FROM (
    SELECT NAME FROM SPORTS_STUD
    UNION
    SELECT NAME FROM CULTURAL_STUD
)
ORDER BY NAME DESC;

-- 14. Drop domain (CHECK) constraints only; keep PK and UNIQUE constraints
ALTER TABLE SPORTS_STUD DROP CONSTRAINT SP_DEPT_CHK;
ALTER TABLE SPORTS_STUD DROP CONSTRAINT SP_FEE_CHK;
ALTER TABLE CULTURAL_STUD DROP CONSTRAINT CU_DEPT_CHK;
ALTER TABLE CULTURAL_STUD DROP CONSTRAINT CU_FEE_CHK;

-- 15. Maximum, minimum and average sports fee
SELECT MAX(SPORTS_FEE) AS MAXIMUM,
       MIN(SPORTS_FEE) AS MINIMUM,
       ROUND(AVG(SPORTS_FEE), 2) AS AVERAGE
FROM SPORTS_STUD;
