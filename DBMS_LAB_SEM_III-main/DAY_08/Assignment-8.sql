-- 2. Distinct students in both groups
SELECT ROLL, NAME, DEPT FROM SPORTS_STUD
UNION
SELECT ROLL, NAME, DEPT FROM CULTURAL_STUD;

-- 3. All students, retaining duplicates
SELECT ROLL, NAME, DEPT FROM SPORTS_STUD
UNION ALL
SELECT ROLL, NAME, DEPT FROM CULTURAL_STUD;

-- 4. Students in both groups
SELECT ROLL, NAME, DEPT FROM SPORTS_STUD
INTERSECT
SELECT ROLL, NAME, DEPT FROM CULTURAL_STUD;

-- 5. Students only in sports
SELECT ROLL, NAME, DEPT FROM SPORTS_STUD
MINUS
SELECT ROLL, NAME, DEPT FROM CULTURAL_STUD;

-- 6. Students only in cultural
