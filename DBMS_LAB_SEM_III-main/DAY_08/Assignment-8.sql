-- 1. Create SPORTS_STUD
CREATE TABLE SPORTS_STUD (
    ROLL NUMBER(3) CONSTRAINT SP_ROLL_PK PRIMARY KEY,
    NAME VARCHAR2(30) CONSTRAINT SP_NAME_UK UNIQUE,
    DEPT VARCHAR2(5) CONSTRAINT SP_DEPT_CHK CHECK (DEPT IN ('IT','CS')),
    SPORTS_FEE NUMBER(6) CONSTRAINT SP_FEE_CHK CHECK (SPORTS_FEE >= 1000)
);

