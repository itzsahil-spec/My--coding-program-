-- 7. Roll, sports fee and cultural fee for students in both groups
SELECT S.ROLL, S.SPORTS_FEE, C.CUL_FEES
FROM SPORTS_STUD S
JOIN CULTURAL_STUD C ON S.ROLL = C.ROLL;

