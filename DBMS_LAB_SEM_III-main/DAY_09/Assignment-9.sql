-- 2. Customer names and movie numbers issued to them
SELECT C.FNAME, C.LNAME, I.MV_NO
FROM CUSTOMER C
JOIN INVOICE I ON C.CUST_ID = I.CUST_ID;

-- 3. Movie number and title issued to Ivan
SELECT M.MV_NO, M.TITLE
FROM MOVIE M
JOIN INVOICE I ON M.MV_NO = I.MV_NO
JOIN CUSTOMER C ON I.CUST_ID = C.CUST_ID
WHERE C.FNAME = 'Ivan';

-- 4. Title, customer ID and movie number for issued movies
SELECT M.TITLE, I.CUST_ID, I.MV_NO
FROM MOVIE M
JOIN INVOICE I ON M.MV_NO = I.MV_NO;

-- 5. Title and type of movies issued to Vandana
SELECT M.TITLE, M.TYPE
FROM MOVIE M
JOIN INVOICE I ON M.MV_NO = I.MV_NO
JOIN CUSTOMER C ON I.CUST_ID = C.CUST_ID
WHERE C.FNAME = 'Vandana';

-- 6. Customers issued an ACTION movie
SELECT DISTINCT C.FNAME, C.LNAME
FROM CUSTOMER C
JOIN INVOICE I ON C.CUST_ID = I.CUST_ID
JOIN MOVIE M ON I.MV_NO = M.MV_NO
WHERE UPPER(M.TYPE) = 'ACTION';

-- 7. Required sentence format for movies with movie number >= 3
SELECT 'The movie taken by ' || C.FNAME || ', ' || C.LNAME ||
       ' is ' || M.TITLE || '.' AS DETAILS
FROM CUSTOMER C
JOIN INVOICE I ON C.CUST_ID = I.CUST_ID
JOIN MOVIE M ON I.MV_NO = M.MV_NO
WHERE M.MV_NO >= 3;

-- 8. Customer issued invoice I10
SELECT C.FNAME, C.LNAME
FROM CUSTOMER C
JOIN INVOICE I ON C.CUST_ID = I.CUST_ID
WHERE I.INV_NO = 'I10';

-- 9. Customers issued a movie before August 1993
SELECT DISTINCT C.FNAME, C.LNAME, C.PHONE, C.AREA
FROM CUSTOMER C
JOIN INVOICE I ON C.CUST_ID = I.CUST_ID
WHERE I.ISSUE_DATE < DATE '1993-08-01';

-- 10. Movie number and title issued to Ivan, Vandana or Ravi
